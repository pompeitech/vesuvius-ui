'use client'

// Every Vesuvius UI export, re-exported through a "use client" boundary.
// Why this file has to exist at all: the package ships as a single bundled
// dist/index.js with no per-file "use client" directives of its own.
//
// Why a *named* re-export list, specifically (not `import * as Vesuvius`
// + spread into one pre-built object, tried first): a components-map
// object built and exported as one value from a "use client" file comes
// back completely empty (`Object.keys` = 0) once a Server Component
// imports it — Next's client-boundary transform instruments each
// individually-named export, not arbitrary derived data crossing back the
// other way. The working pattern is: `export { X } from "pkg"` here, then
// in the Server Component that actually calls `<MDXRemote>`,
// `import * as VesuviusClient from "./vesuvius-client"` and spread
// `{...VesuviusClient}` into the components object *there* — verified by
// bisecting with a single-export repro before writing out the full list
// below.
//
// Regenerate by running, from packages/ui:
//   node -e "import('./dist/index.js').then(m=>console.log(Object.keys(m).sort()))"
// and pasting the sorted list back in below, whenever a component is added
// to or removed from the package's public API.
